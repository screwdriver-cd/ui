export default defineConfig({
  testDir: './specs',
  // Baselines are per platform and per font set, so screenshots live in their own opt-in
  // suite: `npm run test:visual` (E2E_VISUAL=1). See README.md.
  snapshotPathTemplate: '{testDir}/../snapshots/{arg}-{projectName}-{platform}{ext}',
  expect: { toHaveScreenshot: { animations: 'disabled', caret: 'hide' } },
  // An Ember run (E2E_FRAMEWORK=ember) leaves out the rewrite's own tests, and a React run Ember's;
  // see support/ember.ts.
  grepInvert: isEmber ? /@react-only/ : /@ember-only/,
  fullyParallel: true,
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : 'list',
  use: {
    baseURL,
    // Dev builds bake the CSP connect-src from config/local.js, which would
    // block the mocked API host. Production CSP is generated by nginx from the
    // same env vars as supplementary_config.js and is verified separately
    // against the Docker image.
    bypassCSP: !process.env.E2E_ENFORCE_CSP,
    trace: 'retain-on-failure',
    viewport: { width: 1440, height: 900 }
  },
  projects: [{ name: 'chromium', use: { browserName: 'chromium' } }]
});
